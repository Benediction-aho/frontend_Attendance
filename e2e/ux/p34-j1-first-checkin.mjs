// J1: new employee first sign-in -> Face ID registration -> check-in at the office (iPhone).
import * as k from './h34.mjs';
const b = await k.h.launch();
const u = await k.staff('kofi', 'employee', { onboard: false });
const c = await k.ctx(b, process.argv[2] ?? 'iphone');
const p = await c.newPage();
const auth = await k.authenticator(p);
p.on('console', (m) => m.type() === 'error' && k.out('console', m.text().slice(0, 200)));
await k.signIn(p, u.email, u.code);
const cur = p.getByLabel(/Identification code/);
if (await cur.count()) await cur.fill(u.code);
await p.getByLabel('New password', { exact: true }).fill(k.PW);
await p.getByLabel('Confirm new password').fill(k.PW);
await p.getByRole('button', { name: 'Save my password' }).click();
await p.waitForURL(/profile/);
await p.getByLabel('Phone').fill('+233 24 123 4567');
await p.getByRole('button', { name: 'Save and continue' }).click();
await p.waitForURL(/faceid|app/);
k.out('after profile', p.url());
await k.shot(p, (process.argv[2] ?? 'iphone') + '-j1-01-welcome-faceid');
k.out((await k.mainText(p)) || (await p.locator('body').innerText()).slice(0, 600));
await p.getByRole('button', { name: 'Set up Face ID' }).click();
await p.waitForTimeout(2500);
k.out('creds', (await auth.credentials()).length);
await k.shot(p, (process.argv[2] ?? 'iphone') + '-j1-02-faceid-done');
k.out((await p.locator('body').innerText()).replace(/\s+/g, ' ').slice(0, 500));
const cont = p.getByRole('button', { name: /Continue|Go to|Start/ });
if (await cont.count()) await cont.first().click();
await p.waitForURL(/\/app/);
await p.waitForTimeout(1000);
await k.shot(p, (process.argv[2] ?? 'iphone') + '-j1-03-dashboard');
k.out('dash', await k.mainText(p));
await p.goto(k.BASE + '/app/attendance');
await p.waitForTimeout(1200);
await k.shot(p, (process.argv[2] ?? 'iphone') + '-j1-04-today-before');
k.out('today', await k.mainText(p));
await p.getByRole('button', { name: 'Check in at the office' }).click();
for (let i = 0; i < 10; i++) {
  await p.waitForTimeout(500);
  if (i === 1) await k.shot(p, (process.argv[2] ?? 'iphone') + '-j1-05-checking');
}
await k.shot(p, (process.argv[2] ?? 'iphone') + '-j1-06-today-after');
k.out('after checkin', await k.mainText(p));
await p.reload();
await p.waitForTimeout(1500);
k.out('after reload', await k.mainText(p));
const t = await k.call('GET', '/attendance/today', null, null);
console.log(JSON.stringify({ email: u.email }));
await b.close();
